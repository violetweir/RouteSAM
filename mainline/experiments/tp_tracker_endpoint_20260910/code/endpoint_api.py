"""Terminal-step gradients using the unchanged public TP inference state.

History is generated by the current model and detached (one-step truncated
backpropagation). No target label enters prompts, memory or object selection.
"""
import inspect
from contextlib import contextmanager
import numpy as np
import torch
import torch.nn.functional as F

def clone_tree(x):
    if torch.is_tensor(x): return x.detach().clone()
    if isinstance(x,dict): return {k:clone_tree(v) for k,v in x.items()}
    if isinstance(x,list): return [clone_tree(v) for v in x]
    if isinstance(x,tuple): return tuple(clone_tree(v) for v in x)
    return x

class EndpointCapture:
    def __init__(self, model, terminal):
        self.model=model;self.terminal=terminal;self.records=[];self.active_ids=None
        self.single=model.tracker._run_single_frame_inference
        self.track=model.tracker.track_step
        self.single_sig=inspect.signature(self.single)

    def __enter__(self):
        def single(*args,**kwargs):
            bound=self.single_sig.bind(*args,**kwargs).arguments
            state=bound['inference_state']
            previous=self.active_ids
            self.active_ids=list(state['obj_ids'])
            try:return self.single(*args,**kwargs)
            finally:self.active_ids=previous
        def track(*args,**kwargs):
            captured=None
            if kwargs['frame_idx']==self.terminal and not kwargs['is_init_cond_frame']:
                assert kwargs['point_inputs'] is None and kwargs['mask_inputs'] is None
                with torch.inference_mode(False), torch.no_grad():
                    captured=clone_tree(kwargs)
            out=self.track(*args,**kwargs)
            if captured is not None:
                with torch.inference_mode(False),torch.no_grad():
                    self.records.append(dict(kwargs=captured,obj_ids=list(self.active_ids),
                                             expected=out['pred_masks'].detach().clone()))
            return out
        self.model.tracker._run_single_frame_inference=single
        self.model.tracker.track_step=track
        return self

    def __exit__(self,*exc):
        self.model.tracker._run_single_frame_inference=self.single
        self.model.tracker.track_step=self.track

    def replay(self,selected_object_id):
        matches=[r for r in self.records if selected_object_id in r['obj_ids']]
        if len(matches)!=1:raise RuntimeError(f'Expected one terminal track output for object {selected_object_id}; got {len(matches)}')
        r=matches[0];index=r['obj_ids'].index(selected_object_id)
        # Predictor keeps a process-long autocast context. Cached inference casts
        # would sever adapter gradients and become stale after optimizer updates.
        torch.clear_autocast_cache()
        with torch.inference_mode(False),torch.enable_grad(),torch.autocast('cuda',dtype=torch.bfloat16,cache_enabled=False):
            output=self.track(**r['kwargs'])
            logits=output['pred_masks'][index:index+1].float()
            assert logits.requires_grad
        return logits,r['expected'][index:index+1].float()

def public_forward(model,row,load_rgb,select_top,capture=False):
    frames=[load_rgb(p,256) for p in [row['anchor_image_path'],*row['bridge_image_paths'],row['target_image_path']]]
    with torch.inference_mode():
        state=model.init_state(resource_path=frames,offload_video_to_cpu=False,
                               offload_state_to_cpu=False,async_loading_frames=False)
        model.add_prompt(state,frame_idx=0,text_str=None,boxes_xywh=[row['anchor_box_xywh_normalized']],box_labels=[1])
        for frame,out in model.propagate_in_video(state,start_frame_idx=0,max_frame_num_to_track=len(frames),reverse=False):
            if frame==len(frames)-1:final=out
        selected=select_top(final,256)
        if len(final['out_probs']):
            i=int(np.argmax(np.asarray(final['out_probs'])))
            selected['object_id']=int(final['out_obj_ids'][i])
        else:selected['object_id']=None
    return selected

def terminal_loss(logits,target):
    z=F.interpolate(logits,size=target.shape[-2:],mode='bilinear',align_corners=False)
    p=z.sigmoid()
    return F.binary_cross_entropy_with_logits(z,target)+1-(2*(p*target).sum()+1)/(p.sum()+target.sum()+1)
